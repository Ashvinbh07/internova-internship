# Declaring variables

age = 22                           #integer
percentage = 85.5                  #float
name = "Ashvin"                    #string
is_student = True                  #boolean

# Displaying values and their data types

print("Integer value:", age)
print("Data type:", type(age))

print("\nFloat value:", percentage)
print("Data type:", type(percentage))

print("\nString value:", name)
print("Data type:", type(name))

print("\nBoolean value:", is_student)
print("Data type:", type(is_student))